/**
 * Typecheck every TypeScript snippet in the guide.
 *
 * ## The problem this solves
 *
 * A guide's code samples are the part readers copy first and the part that rots first. Prose that goes
 * stale reads oddly; a snippet that goes stale fails in someone's editor, and they conclude the whole
 * library is broken. So every snippet is compiled here, against the real packages, on every verify.
 *
 * ## How it works
 *
 * Every ```ts fence becomes its own module under `.snippets/`. Each one keeps the import lines it
 * already has, at the top, and gains an `export {}` so the compiler treats it as a module. A snippet in
 * this guide is a complete example rather than a fragment, for that reason: the reader copies the file
 * and it runs.
 *
 * ## What it checks
 *
 * That each import resolves, that each name imported from `@mg.js/*` is really exported by that package,
 * and that the body typechecks with those imports in scope. A snippet that calls a method with the wrong
 * arguments, names an action that does not exist, or reads a state path typed by the package fails here.
 *
 * ## What it does not check
 *
 * That a snippet is a whole program. Snippets that need a browser, a canvas or a live socket are still
 * typechecked, but nothing runs them.
 *
 * @see writeSnippetConfig for how `@mg.js/*` is mapped to either the sibling package sources or the
 * installed packages.
 */

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ts = require('typescript');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'content');
const snippetsDir = join(root, '.snippets');

/**
 * Where `@mg.js/*` resolves.
 *
 * Two layouts are supported, in this order:
 *
 *   1. Sibling package sources, when `../mg.js/packages` exists (the monorepo checkout). This is the
 *      stronger check, because it is the source rather than a built declaration, so a snippet is
 *      verified against what the packages do next rather than against whatever was last published.
 *   2. The installed packages in `node_modules`, through their declarations. This is what a standalone
 *      clone of the guide has, and it verifies against the released version the guide documents.
 *
 * `MG_PACKAGES` overrides the first path, for a checkout that lives somewhere else.
 */
function packagesMapping(packagesRoot, installedRoot) {
  const kinds = ['bootstrapped', 'common', 'headless'];
  const mapping = {};
  for (const kind of kinds) {
    const source = join(packagesRoot, kind, 'src/index.ts');
    mapping[`@mg.js/${kind}`] = existsSync(source)
      ? [source]
      : [join(installedRoot, `@mg.js/${kind}/dist/index.d.ts`)];
  }
  return mapping;
}

/**
 * Write the throwaway tsconfig the snippet program reads.
 *
 * Generated rather than committed, because the paths depend on which layout was found above and a
 * committed file would pin one of them.
 */
async function writeSnippetConfig(packagesRoot, installedRoot) {
  const config = {
    compilerOptions: {
      target: 'es2023',
      lib: ['es2023', 'dom', 'dom.iterable'],
      module: 'nodenext',
      moduleResolution: 'nodenext',
      strict: true,
      noUncheckedIndexedAccess: true,
      noImplicitOverride: true,
      noFallthroughCasesInSwitch: true,
      skipLibCheck: true,
      noEmit: true,
      noUnusedLocals: false,
      noUnusedParameters: false,
      paths: packagesMapping(packagesRoot, installedRoot),
    },
    include: ['.snippets/**/*.ts'],
  };
  const path = join(snippetsDir, 'tsconfig.json');
  await writeFile(path, JSON.stringify(config, null, 2), 'utf8');
  return path;
}

function extractSnippets(markdown) {
  const snippets = [];
  const pattern = /^[ \t]*```(ts|typescript)[ \t]*\r?\n([\s\S]*?)^[ \t]*```[ \t]*$/gm;
  let match = pattern.exec(markdown);
  while (match !== null) {
    const code = match[2].replace(/\s+$/, '');
    if (code.trim() !== '') snippets.push(code);
    match = pattern.exec(markdown);
  }
  return snippets;
}

function assemble(code) {
  return [
    '/* Generated from a guide page. Do not edit this file: run `npm run build` instead. */',
    code,
    '',
    'export {};',
    '',
  ].join('\n');
}

function formatDiagnostics(diagnostics, labels) {
  return diagnostics
    .map((diagnostic) => {
      const name = labels.get(diagnostic.file?.fileName) ?? 'snippet';
      const message = ts.flattenDiagnosticMessageText(diagnostic.messageText, ' ');
      if (diagnostic.file === undefined || diagnostic.start === undefined) return `  ${name}: ${message}`;
      const position = diagnostic.file.getLineAndCharacterOfPosition(diagnostic.start);
      return `  ${name}:${position.line + 1}:${position.character + 1}: ${message}`;
    })
    .join('\n');
}

async function main() {
  const files = (await readdir(contentDir)).filter((name) => name.endsWith('.md')).sort();
  await rm(snippetsDir, { recursive: true, force: true });
  await mkdir(snippetsDir, { recursive: true });

  const labels = new Map();
  let count = 0;

  for (const file of files) {
    const markdown = await readFile(join(contentDir, file), 'utf8');
    const snippets = extractSnippets(markdown);
    for (let index = 0; index < snippets.length; index += 1) {
      const name = `${file.replace(/\.md$/, '')}.${String(index + 1).padStart(2, '0')}.ts`;
      const path = join(snippetsDir, name);
      await writeFile(path, assemble(snippets[index]), 'utf8');
      labels.set(path, `${file} snippet ${index + 1}`);
      count += 1;
    }
  }

  if (count === 0) {
    console.log('check:snippets: no TypeScript snippets found');
    return;
  }

  const packagesRoot = process.env.MG_PACKAGES ?? resolve(root, '../mg.js/packages');
  const installedRoot = join(root, 'node_modules');
  const configPath = await writeSnippetConfig(packagesRoot, installedRoot);

  const config = ts.readConfigFile(configPath, (path) => ts.sys.readFile(path));
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, ' '));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, snippetsDir);
  const program = ts.createProgram({ rootNames: parsed.fileNames, options: parsed.options });

  const diagnostics = ts
    .getPreEmitDiagnostics(program)
    // An isolated snippet can leave an import unused, or redeclare nothing at all. Neither is an error here.
    .filter((diagnostic) => diagnostic.code !== 6133 && diagnostic.code !== 6192 && diagnostic.code !== 6196);

  if (diagnostics.length > 0) {
    console.error(formatDiagnostics(diagnostics, labels));
    throw new Error(`check:snippets: ${diagnostics.length} error(s) across ${count} snippet(s).`);
  }

  console.log(`check:snippets: ${count} snippets across ${files.length} pages, no errors.`);
}

await main();
